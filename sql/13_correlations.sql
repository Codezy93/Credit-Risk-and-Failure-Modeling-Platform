-- Pearson correlations on untrimmed development data; NULL pairs are excluded.
WITH correlations AS (
    SELECT
        corr(loan_amnt, loan_amnt) AS loan_amnt__loan_amnt,
        corr(loan_amnt, int_rate) AS loan_amnt__int_rate,
        corr(loan_amnt, annual_inc) AS loan_amnt__annual_inc,
        corr(loan_amnt, dti) AS loan_amnt__dti,
        corr(loan_amnt, revol_util) AS loan_amnt__revol_util,
        corr(loan_amnt, fico_mid) AS loan_amnt__fico_mid,
        corr(loan_amnt, credit_history_years) AS loan_amnt__credit_history_years,
        corr(int_rate, loan_amnt) AS int_rate__loan_amnt,
        corr(int_rate, int_rate) AS int_rate__int_rate,
        corr(int_rate, annual_inc) AS int_rate__annual_inc,
        corr(int_rate, dti) AS int_rate__dti,
        corr(int_rate, revol_util) AS int_rate__revol_util,
        corr(int_rate, fico_mid) AS int_rate__fico_mid,
        corr(int_rate, credit_history_years) AS int_rate__credit_history_years,
        corr(annual_inc, loan_amnt) AS annual_inc__loan_amnt,
        corr(annual_inc, int_rate) AS annual_inc__int_rate,
        corr(annual_inc, annual_inc) AS annual_inc__annual_inc,
        corr(annual_inc, dti) AS annual_inc__dti,
        corr(annual_inc, revol_util) AS annual_inc__revol_util,
        corr(annual_inc, fico_mid) AS annual_inc__fico_mid,
        corr(annual_inc, credit_history_years) AS annual_inc__credit_history_years,
        corr(dti, loan_amnt) AS dti__loan_amnt,
        corr(dti, int_rate) AS dti__int_rate,
        corr(dti, annual_inc) AS dti__annual_inc,
        corr(dti, dti) AS dti__dti,
        corr(dti, revol_util) AS dti__revol_util,
        corr(dti, fico_mid) AS dti__fico_mid,
        corr(dti, credit_history_years) AS dti__credit_history_years,
        corr(revol_util, loan_amnt) AS revol_util__loan_amnt,
        corr(revol_util, int_rate) AS revol_util__int_rate,
        corr(revol_util, annual_inc) AS revol_util__annual_inc,
        corr(revol_util, dti) AS revol_util__dti,
        corr(revol_util, revol_util) AS revol_util__revol_util,
        corr(revol_util, fico_mid) AS revol_util__fico_mid,
        corr(revol_util, credit_history_years) AS revol_util__credit_history_years,
        corr(fico_mid, loan_amnt) AS fico_mid__loan_amnt,
        corr(fico_mid, int_rate) AS fico_mid__int_rate,
        corr(fico_mid, annual_inc) AS fico_mid__annual_inc,
        corr(fico_mid, dti) AS fico_mid__dti,
        corr(fico_mid, revol_util) AS fico_mid__revol_util,
        corr(fico_mid, fico_mid) AS fico_mid__fico_mid,
        corr(fico_mid, credit_history_years) AS fico_mid__credit_history_years,
        corr(credit_history_years, loan_amnt) AS credit_history_years__loan_amnt,
        corr(credit_history_years, int_rate) AS credit_history_years__int_rate,
        corr(credit_history_years, annual_inc) AS credit_history_years__annual_inc,
        corr(credit_history_years, dti) AS credit_history_years__dti,
        corr(credit_history_years, revol_util) AS credit_history_years__revol_util,
        corr(credit_history_years, fico_mid) AS credit_history_years__fico_mid,
        corr(credit_history_years, credit_history_years) AS credit_history_years__credit_history_years
    FROM eda_loans
), long_correlations AS (
    UNPIVOT correlations ON COLUMNS(*) INTO NAME pair VALUE correlation
)
SELECT split_part(pair, '__', 1) AS feature_x,
    split_part(pair, '__', 2) AS feature_y, correlation
FROM long_correlations ORDER BY feature_x, feature_y;
